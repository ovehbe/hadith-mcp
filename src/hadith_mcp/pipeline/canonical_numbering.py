def _raw_int(row: dict[str, Any], key: str) -> int:
    return int(row[key])


def _bukhari_number_by_source_id(source_id: int) -> int:
    for start, end, delta in BUKHARI_CANONICAL_RANGES:
        if start <= source_id <= end:
            return source_id + delta
    raise ValueError(f"No canonical Bukhari reference for source id {source_id}")


def canonical_id_in_book_by_hadith_id(
    collection_slug: str, raw_hadiths: list[dict[str, Any]]
) -> dict[int, int]:
    """Return hadith-json source id -> Sunnah.com-style collection reference number."""
    if collection_slug == "bukhari":
        numbers = {
            _raw_int(h, "id"): _bukhari_number_by_source_id(_raw_int(h, "id"))
            for h in raw_hadiths
        }
        _validate_positive(collection_slug, numbers)
        return numbers

    intro_rows = [h for h in raw_hadiths if _raw_int(h, "chapterId") == 0]
    if intro_rows and len(intro_rows) < len(raw_hadiths):
        intro_start = len(raw_hadiths) - len(intro_rows)
        intro_is_trailing = all(_raw_int(h, "chapterId") == 0 for h in raw_hadiths[intro_start:])
        normal_rows_before_intro = all(
            _raw_int(h, "chapterId") != 0 for h in raw_hadiths[:intro_start]
        )
        if intro_is_trailing and normal_rows_before_intro:
            ordered = [*intro_rows, *raw_hadiths[:intro_start]]
            numbers = {_raw_int(h, "id"): i for i, h in enumerate(ordered, start=1)}
            _validate_positive(collection_slug, numbers)
            return numbers

    numbers = {_raw_int(h, "id"): _raw_int(h, "idInBook") for h in raw_hadiths}
    _validate_positive(collection_slug, numbers)
    return numbers


def _validate_positive(collection_slug: str, numbers: dict[int, int]) -> None:
    if any(v < 1 for v in numbers.values()):
        raise ValueError(f"Canonical numbering for {collection_slug} contains non-positive values")
